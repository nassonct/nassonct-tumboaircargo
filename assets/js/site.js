  const languageKey = "tumbo-air-cargo-language";

  function getLanguage() {
    return localStorage.getItem(languageKey) === "sw" ? "sw" : "en";
  }

  function translate(key, language = getLanguage()) {
    return messages[language][key] || messages.en[key] || key;
  }

  function applyLanguage(language) {
    const selected = language === "sw" ? "sw" : "en";
    document.documentElement.lang = selected;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const value = messages[selected][element.dataset.i18n];
      if (value) element.textContent = value;
    });

    document.querySelectorAll("[data-i18n-content]").forEach((element) => {
      const value = messages[selected][element.dataset.i18nContent];
      if (value) element.setAttribute("content", value);
    });

    document.querySelectorAll("form :required").forEach((control) => {
      if (control.validity.customError) control.setCustomValidity("");
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const value = messages[selected][element.dataset.i18nPlaceholder];
      if (value) element.setAttribute("placeholder", value);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
      const value = messages[selected][element.dataset.i18nAria];
      if (value) element.setAttribute("aria-label", value);
    });

    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      const value = messages[selected][element.dataset.i18nTitle];
      if (value) element.setAttribute("title", value);
    });

    document.querySelectorAll("[data-whatsapp-message]").forEach((element) => {
      element.setAttribute(
        "href",
        createWhatsAppLink(
          element.dataset.whatsappNumber || primaryWhatsApp,
          translate(element.dataset.whatsappMessage, selected),
        ),
      );
    });

    document.querySelectorAll("[data-language-choice]").forEach((button) => {
      const active = button.dataset.languageChoice === selected;
      button.setAttribute("aria-pressed", String(active));
      button.classList.toggle("is-active", active);
    });

    document
      .querySelectorAll("[data-language-switcher]")
      .forEach((switcher) => {
        switcher.setAttribute(
          "aria-label",
          translate("language.label", selected),
        );
      });

    document.querySelectorAll("[data-menu-toggle]").forEach((toggle) => {
      const key =
        toggle.getAttribute("aria-expanded") === "true"
          ? "menu.close"
          : "menu.open";
      toggle.setAttribute("aria-label", translate(key, selected));
    });

    localStorage.setItem(languageKey, selected);
  }

  function createLanguageSwitchers() {
    document.querySelectorAll("header").forEach((header) => {
      const actions = header.querySelector("button")?.parentElement;
      if (!actions || actions.querySelector("[data-language-switcher]")) return;

      const switcher = document.createElement("div");
      switcher.className = "language-switcher";
      switcher.dataset.languageSwitcher = "";
      switcher.setAttribute("role", "group");
      switcher.setAttribute("aria-label", translate("language.label"));

      for (const language of ["en", "sw"]) {
        const button = document.createElement("button");
        button.className = "language-switcher__button";
        button.type = "button";
        button.textContent = language.toUpperCase();
        button.dataset.languageChoice = language;
        button.addEventListener("click", () => applyLanguage(language));
        switcher.append(button);
      }

      actions.prepend(switcher);
    });
  }

  function setupMobileNavigation() {
    document.querySelectorAll("header").forEach((header) => {
      const navigation = header.querySelector("nav");
      const toggle =
        header.querySelector(
          "button[aria-label*='Menu'], button[aria-label*='menu']",
        ) ||
        [...header.querySelectorAll("button")].find((button) =>
          button
            .querySelector(".material-symbols-outlined")
            ?.textContent.trim()
            .includes("menu"),
        );
      if (!navigation || !toggle) return;

      if (!navigation.id) navigation.id = "primary-navigation";
      navigation.dataset.mobileNavigation = "";
      toggle.dataset.menuToggle = "";
      toggle.setAttribute("aria-controls", navigation.id);
      toggle.setAttribute("aria-expanded", "false");
      toggle.setAttribute("aria-label", translate("menu.open"));

      toggle.addEventListener("click", () => {
        const isOpen = navigation.dataset.mobileOpen !== "true";
        navigation.dataset.mobileOpen = String(isOpen);
        toggle.setAttribute("aria-expanded", String(isOpen));
        toggle.setAttribute(
          "aria-label",
          translate(isOpen ? "menu.close" : "menu.open"),
        );
      });

      navigation.querySelectorAll("a").forEach((link) => {
        link.addEventListener("click", () => {
          navigation.dataset.mobileOpen = "false";
          toggle.setAttribute("aria-expanded", "false");
          toggle.setAttribute("aria-label", translate("menu.open"));
        });
      });
    });
  }

  function createWhatsAppLink(number, message) {
    return `https://wa.me/${number}?text=${encodeURIComponent(message)}`;
  }

  function openWhatsApp(message, number = primaryWhatsApp) {
    window.location.assign(createWhatsAppLink(number, message));
  }

  function formValue(form, name) {
    const control =
      form.querySelector(`[name="${name}"]`) || form.querySelector(`#${name}`);
    return control ? control.value.trim() : "";
  }

  function formDisplayValue(form, name) {
    const control = form.querySelector(`[name="${name}"]`);
    if (control instanceof HTMLSelectElement) {
      return control.selectedOptions[0]?.textContent.trim() || "";
    }
    return formValue(form, name);
  }

  function setupFormValidation() {
    document.querySelectorAll("form").forEach((form) => {
      form.querySelectorAll(":required").forEach((control) => {
        control.addEventListener("invalid", () => {
          if (control.validity.valueMissing) {
            control.setCustomValidity(translate("form.required"));
          } else if (
            control.validity.typeMismatch &&
            control.type === "email"
          ) {
            control.setCustomValidity(translate("form.email"));
          } else if (
            control.type === "tel" &&
            (control.validity.patternMismatch ||
              control.validity.tooShort ||
              control.validity.tooLong)
          ) {
            control.setCustomValidity(translate("form.phone"));
          }
        });
        control.addEventListener("input", () => control.setCustomValidity(""));
        control.addEventListener("change", () => control.setCustomValidity(""));
      });
    });
  }

  function setupTrackingForms() {
    document.querySelectorAll("[data-tracking-form]").forEach((form) => {
      form.addEventListener("submit", (event) => {
        event.preventDefault();
        const status = document.querySelector("[data-tracking-status]");
        if (!status) return;
        status.textContent = translate("tracking.notConnected");
        status.classList.remove("hidden");
        status.focus();
      });
    });
  }

  function setupContactForm() {
    const form = document.getElementById("contactForm");
    if (!form) return;

    form.addEventListener("submit", (event) => {
      event.preventDefault();
      if (!form.reportValidity()) return;

      const lines = [
        translate("whatsapp.greeting"),
        "",
        translate("whatsapp.inquiry"),
        `${translate("whatsapp.name")}: ${formValue(form, "fullName")}`,
        `${translate("whatsapp.phone")}: ${formValue(form, "phoneNumber")}`,
        `${translate("whatsapp.email")}: ${formValue(form, "emailAddress") || translate("whatsapp.notProvided")}`,
        `${translate("whatsapp.subject")}: ${formValue(form, "subject")}`,
        `${translate("whatsapp.message")}: ${formValue(form, "messageContent")}`,
      ];
      openWhatsApp(lines.join("\n"));
    });
  }

